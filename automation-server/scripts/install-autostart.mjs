#!/usr/bin/env node
// Windows: start the automation service automatically and invisibly every time you sign in,
// independent of Chrome. Uses Task Scheduler (current user, no admin rights needed):
//   - trigger: at logon of the current user (+30 s delay)
//   - action:  wscript.exe run-hidden.vbs → node (no console window)
//   - restarts automatically if the service crashes; no run-time limit; runs on battery
//   npm run autostart:install     npm run autostart:uninstall     npm run autostart:status
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const TASK = 'TaskPilot';
/** Names of earlier TaskPilot tasks to remove on install (none yet). */
const OLD_TASKS = [];
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const cmd = process.argv[2] ?? 'install';

if (process.platform !== 'win32') {
  console.error('Auto-start via Task Scheduler is Windows-only. On macOS/Linux use a LaunchAgent / systemd user unit running "npm start".');
  process.exit(1);
}

const schtasks = (...args) => execFileSync('schtasks.exe', args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });

if (cmd === 'uninstall') {
  try {
    schtasks('/Delete', '/TN', TASK, '/F');
    console.log(`Removed scheduled task "${TASK}". The service will no longer start at sign-in.`);
  } catch {
    console.log('Auto-start was not installed.');
  }
  process.exit(0);
}

if (cmd === 'status') {
  try {
    console.log(schtasks('/Query', '/TN', TASK, '/V', '/FO', 'LIST').split('\n').filter((l) => /TaskName|Status|Last Run Time|Last Result|Next Run Time|Schedule Type/i.test(l)).join('\n'));
  } catch {
    console.log('Auto-start is not installed.');
  }
  process.exit(0);
}

// --- install ---------------------------------------------------------------------------------
const dir = path.join(root, 'data', 'autostart');
fs.mkdirSync(dir, { recursive: true });
const tsxCli = path.join(root, 'node_modules', 'tsx', 'dist', 'cli.mjs');
const serverTs = path.join(root, 'automation-server', 'src', 'main.ts');
const q = (s) => `""${s}""`; // VBScript-escaped double quotes
const vbs = path.join(dir, 'run-hidden.vbs');
fs.writeFileSync(
  vbs,
  [
    "' Starts the TaskPilot service with no window. Generated by install-autostart.mjs.",
    'Set sh = CreateObject("WScript.Shell")',
    `sh.CurrentDirectory = "${root}"`,
    `WScript.Quit sh.Run("${q(process.execPath)} ${q(tsxCli)} ${q(serverTs)}", 0, True)`,
    '',
  ].join('\r\n'),
);

const user = `${process.env.USERDOMAIN}\\${process.env.USERNAME}`;
const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const xml = `<?xml version="1.0" encoding="UTF-16"?>
<Task version="1.4" xmlns="http://schemas.microsoft.com/windows/2004/02/mit/task">
  <RegistrationInfo>
    <Description>Runs the TaskPilot automation service in the background so scheduled automations run automatically.</Description>
  </RegistrationInfo>
  <Triggers>
    <LogonTrigger>
      <Enabled>true</Enabled>
      <UserId>${esc(user)}</UserId>
      <Delay>PT30S</Delay>
    </LogonTrigger>
  </Triggers>
  <Principals>
    <Principal id="Author">
      <UserId>${esc(user)}</UserId>
      <LogonType>InteractiveToken</LogonType>
      <RunLevel>LeastPrivilege</RunLevel>
    </Principal>
  </Principals>
  <Settings>
    <MultipleInstancesPolicy>IgnoreNew</MultipleInstancesPolicy>
    <DisallowStartIfOnBatteries>false</DisallowStartIfOnBatteries>
    <StopIfGoingOnBatteries>false</StopIfGoingOnBatteries>
    <AllowHardTerminate>true</AllowHardTerminate>
    <StartWhenAvailable>true</StartWhenAvailable>
    <RunOnlyIfNetworkAvailable>false</RunOnlyIfNetworkAvailable>
    <IdleSettings><StopOnIdleEnd>false</StopOnIdleEnd><RestartOnIdle>false</RestartOnIdle></IdleSettings>
    <AllowStartOnDemand>true</AllowStartOnDemand>
    <Enabled>true</Enabled>
    <Hidden>false</Hidden>
    <RunOnlyIfIdle>false</RunOnlyIfIdle>
    <WakeToRun>false</WakeToRun>
    <ExecutionTimeLimit>PT0S</ExecutionTimeLimit>
    <Priority>7</Priority>
    <RestartOnFailure><Interval>PT1M</Interval><Count>999</Count></RestartOnFailure>
  </Settings>
  <Actions Context="Author">
    <Exec>
      <Command>wscript.exe</Command>
      <Arguments>"${esc(vbs)}"</Arguments>
      <WorkingDirectory>${esc(root)}</WorkingDirectory>
    </Exec>
  </Actions>
</Task>
`;
const xmlPath = path.join(dir, 'task.xml');
fs.writeFileSync(xmlPath, Buffer.concat([Buffer.from([0xff, 0xfe]), Buffer.from(xml, 'utf16le')]));
for (const old of OLD_TASKS) {
  try {
    schtasks('/Delete', '/TN', old, '/F');
    console.log(`Removed old scheduled task "${old}".`);
  } catch {
    /* not present */
  }
}
schtasks('/Create', '/TN', TASK, '/XML', xmlPath, '/F');
console.log(`Scheduled task "${TASK}" installed: the service now starts hidden every time you sign in to Windows.`);

if (process.argv.includes('--start')) {
  schtasks('/Run', '/TN', TASK);
  console.log('Started it now.');
}
